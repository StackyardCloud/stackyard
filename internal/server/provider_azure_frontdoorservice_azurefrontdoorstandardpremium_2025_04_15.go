// Azure Front Door Standard and Premium (Microsoft.Cdn, api-version
// 2025-04-15): endpoints with routes, origin groups with origins, custom
// domains, rule sets with rules, secrets and security policies, served by
// the shared ARM handler under a Microsoft.Cdn profile. Profiles themselves
// stay with the CDN router, which mirrors each into the ARM store as their
// parent (see azure_frontdoorservice_azurefrontdoorstandardpremium_2025_04_15_profiles.go).
// Nothing is deployed to an edge: every resource reports Succeeded, and
// custom domains are approved without a DNS check.
const azureAfdxNamespace = "Microsoft.Cdn"

var (
	azureAfdxEndpointName = regexp.MustCompile(`^[a-zA-Z0-9]+([-a-zA-Z0-9]*[a-zA-Z0-9]+)?$`)
	azureAfdxRuleSetName  = regexp.MustCompile(`^[a-zA-Z][a-zA-Z0-9]{0,59}$`)
	azureAfdxSecretTypes  = []string{"UrlSigningKey", "CustomerCertificate", "ManagedCertificate", "AzureFirstPartyManagedCertificate"}
	azureAfdxOnOff        = []string{"Enabled", "Disabled"}
)

// azureAfdxMaxItems bounds lists clients send: patterns, actions,
// conditions, associations and domains.
const azureAfdxMaxItems = 100

func init() {
	ns := azureAfdxNamespace
	deployed := func(parent string) func(*azureARMResource) map[string]any {
		return func(rec *azureARMResource) map[string]any {
			out := map[string]any{"deploymentStatus": "Succeeded"}
			if parent != "" {
				out[parent+"Name"] = azureAfdxSegment(rec.ID, parent)
			}
			return out
		}
	}
	usages := map[string]func(*Server, *azureARMResource, map[string]any) (int, any){"usages": azureAfdxUsages}
	registerAzureARMResourceType(azureARMResourceType{
		Namespace: ns, Type: "profiles/afdEndpoints",
		ValidateName: func(name string) string {
			if len(name) > 46 || !azureAfdxEndpointName.MatchString(name) {
				return "The endpoint name is invalid: use up to 46 letters, digits and hyphens, starting and ending with a letter or digit."
			}
			return ""
		},
		Validate: func(payload map[string]any) string {
			return azureWorkloadsEnums(azureARMObject(payload["properties"]), "properties.", nil, map[string][]string{
				"enabledState": azureAfdxOnOff, "autoGeneratedDomainNameLabelScope": {"TenantReuse", "SubscriptionReuse", "ResourceGroupReuse", "NoReuse"},
			})
		},
		Reconcile: azureAfdxInFrontDoorProfile,
		ReadOnlyProperties: func(rec *azureARMResource) map[string]any {
			return map[string]any{"deploymentStatus": "Succeeded", "profileName": azureAfdxSegment(rec.ID, "profile"), "hostName": azureAfdxHostName(rec)}
		},
		Actions:       map[string]azureARMAction{"purge": azureAfdcPurge, "validatecustomdomain": azureAfdcValidateCustomDomain},
		ServerActions: usages,
	})
	registerAzureARMResourceType(azureARMResourceType{
		Namespace: ns, Type: "profiles/afdEndpoints/routes", Proxy: true,
		Validate:           azureAfdxValidateRoute,
		Reconcile:          azureAfdxCheckRouteReferences,
		ReadOnlyProperties: deployed("endpoint"),
	})
	registerAzureARMResourceType(azureARMResourceType{
		Namespace: ns, Type: "profiles/originGroups", Proxy: true,
		Validate:           azureAfdxValidateOriginGroup,
		Reconcile:          azureAfdxInFrontDoorProfile,
		ReadOnlyProperties: deployed("profile"),
		ServerActions:      usages,
	})
	registerAzureARMResourceType(azureARMResourceType{
		Namespace: ns, Type: "profiles/originGroups/origins", Proxy: true,
		Validate: func(payload map[string]any) string {
			return azureAfdxValidateOrigin(azureARMObject(payload["properties"]))
		},
		ReadOnlyProperties: deployed("originGroup"),
	})
	registerAzureARMResourceType(azureARMResourceType{
		Namespace: ns, Type: "profiles/customDomains", Proxy: true,
		Validate:           azureAfdxValidateCustomDomain,
		Reconcile:          azureAfdxCheckCustomDomain,
		ReadOnlyProperties: azureAfdxCustomDomainProperties,
		Actions: map[string]azureARMAction{"refreshvalidationtoken": func(*azureARMResource, map[string]any) (int, any) {
			return http.StatusOK, nil
		}},
	})
	registerAzureARMResourceType(azureARMResourceType{
		Namespace: ns, Type: "profiles/ruleSets", Proxy: true, NoPatch: true,
		ValidateName: func(name string) string {
			if !azureAfdxRuleSetName.MatchString(name) {
				return "The rule set name is invalid: use up to 60 letters and digits, starting with a letter."
			}
			return ""
		},
		Reconcile:          azureAfdxInFrontDoorProfile,
		ReadOnlyProperties: deployed("profile"),
		ServerActions:      usages,
	})
	registerAzureARMResourceType(azureARMResourceType{
		Namespace: ns, Type: "profiles/ruleSets/rules", Proxy: true,
		Validate:           azureAfdxValidateRule,
		ReadOnlyProperties: deployed("ruleSet"),
	})
	registerAzureARMResourceType(azureARMResourceType{
		Namespace: ns, Type: "profiles/secrets", Proxy: true, NoPatch: true,
		Validate:           azureAfdxValidateSecret,
		Reconcile:          azureAfdxInFrontDoorProfile,
		ReadOnlyProperties: azureAfdxSecretProperties,
	})
	registerAzureARMResourceType(azureARMResourceType{
		Namespace: ns, Type: "profiles/securityPolicies", Proxy: true,
		Validate:           azureAfdxValidateSecurityPolicy,
		Reconcile:          azureAfdxCheckSecurityPolicy,
		ReadOnlyProperties: deployed("profile"),
	})
}

// azureAfdxSegment returns the name after the {kind}s segment of id, such
// as the profile name for kind "profile".
func azureAfdxSegment(id, kind string) string {
	parts := strings.Split(id, "/")
	for i := len(parts) - 2; i >= 0; i-- {
		if strings.EqualFold(parts[i], kind+"s") || strings.EqualFold(parts[i], "afd"+kind+"s") {
			return parts[i+1]
		}
	}
	return ""
}

// azureAfdxProfileID is the profile part of a Front Door resource ID.
func azureAfdxProfileID(id string) string {
	i := strings.Index(strings.ToLower(id), "/profiles/")
	if i < 0 {
		return ""
	}
	rest := id[i+len("/profiles/"):]
	if j := strings.Index(rest, "/"); j >= 0 {
		rest = rest[:j]
	}
	return id[:i] + "/profiles/" + rest
}

func azureAfdxHostName(rec *azureARMResource) string {
	return strings.ToLower(rec.Name) + "-" + azureWorkloadsHash(rec.ID, 16) + ".z01.azurefd.net"
}

// azureAfdxInFrontDoorProfile requires the parent profile to be an Azure
// Front Door Standard or Premium profile. Caller holds the store lock.
func azureAfdxInFrontDoorProfile(s *Server, _, rec *azureARMResource) (map[string]any, string) {
	profile := s.azureARMResources[azureARMKey(azureAfdxProfileID(rec.ID))]
	if profile == nil || !strings.HasSuffix(azureARMString(profile.SKU["name"]), "_AzureFrontDoor") {
		return nil, "The profile must be an Azure Front Door profile (sku Standard_AzureFrontDoor or Premium_AzureFrontDoor)."
	}
	return nil, ""
}

// azureAfdxRefInProfile reports a message unless ref names a stored
// resource of kind (such as "originGroups") in the same profile.
func (s *Server) azureAfdxRefInProfileLocked(profileID, kind, at string, ref any) string {
	id := azureARMString(azureARMObject(ref)["id"])
	if id == "" {
		return at + ".id is required."
	}
	if !strings.HasPrefix(azureARMKey(id), azureARMKey(profileID+"/"+kind+"/")) || s.azureARMResources[azureARMKey(id)] == nil {
		return at + " refers to " + id + ", which is not a " + kind + " resource of this profile."
	}
	return ""
}

func azureAfdxValidatePatterns(props map[string]any, key string) string {
	patterns := azureARMSlice(props[key])
	if len(patterns) > azureAfdxMaxItems {
		return fmt.Sprintf("properties.%s is invalid: at most %d patterns.", key, azureAfdxMaxItems)
	}
	for i, p := range patterns {
		if !strings.HasPrefix(azureARMString(p), "/") {
			return fmt.Sprintf("properties.%s[%d] is invalid: it must start with /.", key, i)
		}
	}
	return ""
}

func azureAfdxValidateRoute(payload map[string]any) string {
	props := azureARMObject(payload["properties"])
	if azureARMString(azureARMObject(props["originGroup"])["id"]) == "" {
		return "properties.originGroup.id is required."
	}
	if msg := azureWorkloadsEnums(props, "properties.", nil, map[string][]string{
		"forwardingProtocol": {"HttpOnly", "HttpsOnly", "MatchRequest"}, "httpsRedirect": azureAfdxOnOff,
		"linkToDefaultDomain": azureAfdxOnOff, "enabledState": azureAfdxOnOff,
	}); msg != "" {
		return msg
	}
	for _, p := range azureARMSlice(props["supportedProtocols"]) {
		if !slices.Contains([]string{"Http", "Https"}, azureARMString(p)) {
			return "properties.supportedProtocols must hold Http or Https."
		}
	}
	return azureAfdxValidatePatterns(props, "patternsToMatch")
}

// azureAfdxCheckRouteReferences requires the route's origin group, custom
// domains and rule sets to exist in its profile, and fills in defaults.
func azureAfdxCheckRouteReferences(s *Server, _, rec *azureARMResource) (map[string]any, string) {
	profileID := azureAfdxProfileID(rec.ID)
	if msg := s.azureAfdxRefInProfileLocked(profileID, "originGroups", "properties.originGroup", rec.Properties["originGroup"]); msg != "" {
		return nil, msg
	}
	for kind, key := range map[string]string{"customDomains": "customDomains", "ruleSets": "ruleSets"} {
		refs := azureARMSlice(rec.Properties[key])
		if len(refs) > azureAfdxMaxItems {
			return nil, fmt.Sprintf("properties.%s is invalid: at most %d references.", key, azureAfdxMaxItems)
		}
		for i, ref := range refs {
			if msg := s.azureAfdxRefInProfileLocked(profileID, kind, fmt.Sprintf("properties.%s[%d]", key, i), ref); msg != "" {
				return nil, msg
			}
		}
	}
	defaults := map[string]any{}
	for key, value := range map[string]any{
		"patternsToMatch": []any{"/*"}, "supportedProtocols": []any{"Http", "Https"}, "forwardingProtocol": "MatchRequest",
		"httpsRedirect": "Disabled", "linkToDefaultDomain": "Disabled", "enabledState": "Enabled", "customDomains": []any{}, "ruleSets": []any{},
	} {
		if _, ok := rec.Properties[key]; !ok {
			defaults[key] = value
		}
	}
	return defaults, ""
}

func azureAfdxValidateOriginGroup(payload map[string]any) string {
	props := azureARMObject(payload["properties"])
	if msg := azureWorkloadsEnums(props, "properties.", nil, map[string][]string{"sessionAffinityState": azureAfdxOnOff}); msg != "" {
		return msg
	}
	probe := azureARMObject(props["healthProbeSettings"])
	if msg := azureWorkloadsEnums(probe, "properties.healthProbeSettings.", nil, map[string][]string{
		"probeProtocol": {"NotSet", "Http", "Https"}, "probeRequestType": {"NotSet", "GET", "HEAD"},
	}); msg != "" {
		return msg
	}
	if raw, ok := probe["probeIntervalInSeconds"]; ok {
		if n, ok := raw.(float64); !ok || n < 1 || n > 255 || n != float64(int(n)) {
			return "properties.healthProbeSettings.probeIntervalInSeconds must be an integer from 1 to 255."
		}
	}
	return ""
}

func azureAfdxValidateOrigin(props map[string]any) string {
	if strings.TrimSpace(azureARMString(props["hostName"])) == "" {
		return "properties.hostName is required."
	}
	backend := map[string]any{"address": props["hostName"]}
	for _, key := range []string{"httpPort", "httpsPort", "priority", "weight", "enabledState"} {
		if v, ok := props[key]; ok {
			backend[key] = v
		}
	}
	return azureAfdcValidateBackend(backend, "properties.")
}

func azureAfdxValidateCustomDomain(payload map[string]any) string {
	props := azureARMObject(payload["properties"])
	if strings.TrimSpace(azureARMString(props["hostName"])) == "" {
		return "properties.hostName is required."
	}
	tls := azureARMObject(props["tlsSettings"])
	if msg := azureWorkloadsEnums(tls, "properties.tlsSettings.", nil, map[string][]string{
		"certificateType":   {"CustomerCertificate", "ManagedCertificate", "AzureFirstPartyManagedCertificate"},
		"minimumTlsVersion": {"TLS10", "TLS12", "TLS13"},
	}); msg != "" {
		return msg
	}
	if tls["certificateType"] == "CustomerCertificate" && azureARMString(azureARMObject(tls["secret"])["id"]) == "" {
		return "properties.tlsSettings.secret.id is required for a CustomerCertificate."
	}
	return ""
}

func azureAfdxCheckCustomDomain(s *Server, existing, rec *azureARMResource) (map[string]any, string) {
	if _, msg := azureAfdxInFrontDoorProfile(s, existing, rec); msg != "" {
		return nil, msg
	}
	if secret, ok := azureARMObject(rec.Properties["tlsSettings"])["secret"]; ok {
		if msg := s.azureAfdxRefInProfileLocked(azureAfdxProfileID(rec.ID), "secrets", "properties.tlsSettings.secret", secret); msg != "" {
			return nil, msg
		}
	}
	return nil, ""
}

// azureAfdxCustomDomainProperties approves the domain at once and issues
// the validation token a client would publish as a DNS TXT record.
func azureAfdxCustomDomainProperties(rec *azureARMResource) map[string]any {
	return map[string]any{
		"deploymentStatus": "Succeeded", "profileName": azureAfdxSegment(rec.ID, "profile"), "domainValidationState": "Approved",
		"validationProperties": map[string]any{
			"validationToken": azureWorkloadsHash(rec.ID+rec.UpdatedAt.String(), 32),
			"expirationDate":  rec.UpdatedAt.Add(7 * 24 * time.Hour).Format(time.RFC3339),
		},
	}
}

func azureAfdxValidateRule(payload map[string]any) string {
	props := azureARMObject(payload["properties"])
	if n, ok := props["order"].(float64); !ok || n < 0 || n != float64(int(n)) {
		return "properties.order is required: a non-negative integer."
	}
	actions := azureARMSlice(props["actions"])
	if len(actions) == 0 || len(actions) > azureAfdxMaxItems {
		return fmt.Sprintf("properties.actions is missing or invalid: list 1 to %d actions.", azureAfdxMaxItems)
	}
	for _, key := range []string{"actions", "conditions"} {
		items := azureARMSlice(props[key])
		if len(items) > azureAfdxMaxItems {
			return fmt.Sprintf("properties.%s is invalid: at most %d items.", key, azureAfdxMaxItems)
		}
		for i, raw := range items {
			if azureARMString(azureARMObject(raw)["name"]) == "" {
				return fmt.Sprintf("properties.%s[%d].name is required.", key, i)
			}
		}
	}
	return azureWorkloadsEnums(props, "properties.", nil, map[string][]string{"matchProcessingBehavior": {"Continue", "Stop"}})
}

func azureAfdxValidateSecret(payload map[string]any) string {
	params := azureARMObject(azureARMObject(payload["properties"])["parameters"])
	if msg := azureWorkloadsEnums(params, "properties.parameters.", []string{"type"}, map[string][]string{"type": azureAfdxSecretTypes}); msg != "" {
		return msg
	}
	switch params["type"] {
	case "CustomerCertificate", "UrlSigningKey":
		if azureARMString(azureARMObject(params["secretSource"])["id"]) == "" {
			return "properties.parameters.secretSource.id is required: the Key Vault secret holding the " + azureARMString(params["type"]) + "."
		}
	}
	if params["type"] == "UrlSigningKey" && azureARMString(params["keyId"]) == "" {
		return "properties.parameters.keyId is required for a UrlSigningKey."
	}
	return ""
}

// azureAfdxSecretProperties reports certificate details for a customer
// certificate; the Key Vault secret is not read.
func azureAfdxSecretProperties(rec *azureARMResource) map[string]any {
	out := map[string]any{"deploymentStatus": "Succeeded", "profileName": azureAfdxSegment(rec.ID, "profile")}
	params := azureARMObject(rec.Properties["parameters"])
	if params["type"] == "CustomerCertificate" {
		out["parameters"] = azureARMMerge(params, map[string]any{
			"subject": "CN=" + rec.Name, "certificateAuthority": "Stackyard Test CA", "subjectAlternativeNames": []any{rec.Name},
			"thumbprint": strings.ToUpper(azureWorkloadsHash(rec.ID, 40)), "expirationDate": rec.CreatedAt.AddDate(1, 0, 0).Format(time.RFC3339),
		})
	}
	return out
}

func azureAfdxValidateSecurityPolicy(payload map[string]any) string {
	params := azureARMObject(azureARMObject(payload["properties"])["parameters"])
	if msg := azureWorkloadsEnums(params, "properties.parameters.", []string{"type"}, map[string][]string{"type": {"WebApplicationFirewall"}}); msg != "" {
		return msg
	}
	if azureARMString(azureARMObject(params["wafPolicy"])["id"]) == "" {
		return "properties.parameters.wafPolicy.id is required."
	}
	associations := azureARMSlice(params["associations"])
	if len(associations) == 0 || len(associations) > azureAfdxMaxItems {
		return fmt.Sprintf("properties.parameters.associations is missing or invalid: list 1 to %d associations.", azureAfdxMaxItems)
	}
	for i, raw := range associations {
		domains := azureARMSlice(azureARMObject(raw)["domains"])
		if len(domains) == 0 || len(domains) > azureAfdxMaxItems {
			return fmt.Sprintf("properties.parameters.associations[%d].domains is missing or invalid: list 1 to %d domains.", i, azureAfdxMaxItems)
		}
		if msg := azureAfdxValidatePatterns(azureARMObject(raw), "patternsToMatch"); msg != "" {
			return strings.Replace(msg, "properties.", fmt.Sprintf("properties.parameters.associations[%d].", i), 1)
		}
	}
	return ""
}

// azureAfdxCheckSecurityPolicy requires each associated domain to be an
// endpoint or custom domain of the same profile.
func azureAfdxCheckSecurityPolicy(s *Server, existing, rec *azureARMResource) (map[string]any, string) {
	if _, msg := azureAfdxInFrontDoorProfile(s, existing, rec); msg != "" {
		return nil, msg
	}
	profileID := azureAfdxProfileID(rec.ID)
	for i, raw := range azureARMSlice(azureARMObject(rec.Properties["parameters"])["associations"]) {
		for j, domain := range azureARMSlice(azureARMObject(raw)["domains"]) {
			at := fmt.Sprintf("properties.parameters.associations[%d].domains[%d]", i, j)
			if s.azureAfdxRefInProfileLocked(profileID, "afdEndpoints", at, domain) != "" {
				if msg := s.azureAfdxRefInProfileLocked(profileID, "customDomains", at, domain); msg != "" {
					return nil, at + " must be an endpoint or custom domain of this profile."
				}
			}
		}
	}
	return nil, ""
}

// azureAfdxUsages reports how many children of each kind the resource has
// against the service limits.
func azureAfdxUsages(s *Server, rec *azureARMResource, _ map[string]any) (int, any) {
	kinds := map[string][2]any{
		"Microsoft.Cdn/profiles/afdEndpoints": {"routes", 100.0},
		"Microsoft.Cdn/profiles/originGroups": {"origins", 50.0},
		"Microsoft.Cdn/profiles/ruleSets":     {"rules", 100.0},
	}
	kind, ok := kinds[rec.Type]
	if !ok {
		return azureOracleBad("usages are not reported for this resource.")
	}
	child := azureARMString(kind[0])
	count := len(s.azureARMResourcesWhere(func(o *azureARMResource) bool {
		return strings.EqualFold(o.Type, rec.Type+"/"+child) && strings.HasPrefix(azureARMKey(o.ID), azureARMKey(rec.ID+"/"))
	}))
	return http.StatusOK, map[string]any{"value": []any{azureAfdxUsage(rec.ID, child, count, kind[1].(float64))}}
}

func azureAfdxUsage(id, name string, current int, limit float64) map[string]any {
	return map[string]any{
		"id": id, "unit": "Count", "currentValue": current, "limit": limit,
		"name": map[string]any{"value": name, "localizedValue": strings.ToUpper(name[:1]) + name[1:]},
	}
}

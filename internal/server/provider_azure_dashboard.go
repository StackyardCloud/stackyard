// Microsoft.Dashboard Azure Managed Grafana workspaces with their managed
// private endpoints and integration fabrics, and managed dashboards, served
// by the shared ARM handler. No Grafana runs: the endpoint is a stable URL
// that serves nothing, and managed private endpoints wait for an approval
// that never comes.
func init() {
	const ns = "Microsoft.Dashboard"
	registerAzureARMResourceType(azureARMResourceType{
		Namespace: ns, Type: "grafana",
		ValidateName:        azureGrafanaName(28),
		Validate:            azureGrafanaValidate,
		ReadOnlyProperties:  azureGrafanaProperties,
		WriteOnlyProperties: []string{"grafanaConfigurations.smtp.password"},
		Actions: map[string]azureARMAction{
			"checkenterprisedetails": func(*azureARMResource, map[string]any) (int, any) {
				return http.StatusOK, map[string]any{"marketplaceTrialQuota": map[string]any{"availablePromotion": "None"}}
			},
			"fetchavailableplugins": func(*azureARMResource, map[string]any) (int, any) {
				return http.StatusOK, map[string]any{"value": azureGrafanaPlugins}
			},
			"refreshmanagedprivateendpoints": func(*azureARMResource, map[string]any) (int, any) { return http.StatusOK, nil },
		},
	})
	registerAzureARMResourceType(azureARMResourceType{
		Namespace: ns, Type: "grafana/managedPrivateEndpoints",
		ValidateName: azureGrafanaName(28),
		Validate:     azureGrafanaManagedPrivateEndpointValidate,
		ReadOnlyProperties: func(*azureARMResource) map[string]any {
			return map[string]any{"connectionState": map[string]any{"status": "Pending", "description": "Awaiting approval by the target resource's owner."}}
		},
	})
	registerAzureARMResourceType(azureARMResourceType{
		Namespace: ns, Type: "grafana/integrationFabrics",
		ValidateName: azureGrafanaName(18),
		Validate:     azureGrafanaIntegrationFabricValidate,
	})
	registerAzureARMView(ns, "grafana/privateLinkResources", func(_ *Server, scope string) []map[string]any {
		return []map[string]any{{
			"id": scope + "/privateLinkResources/grafana", "name": "grafana", "type": "Microsoft.Dashboard/grafana/privateLinkResources",
			"properties": map[string]any{"provisioningState": "Succeeded", "groupId": "grafana", "requiredMembers": []any{"grafana"}, "requiredZoneNames": []any{"privatelink.grafana.azure.com"}},
		}}
	})
	registerAzureARMResourceType(azureARMResourceType{Namespace: ns, Type: "dashboards", ValidateName: azureGrafanaName(28)})
}

// azureGrafanaName returns the Microsoft.Dashboard name rule: a letter, then
// up to inner letters, digits or hyphens, ending in a letter or digit.
func azureGrafanaName(inner int) func(string) string {
	pattern := regexp.MustCompile(fmt.Sprintf(`^[a-zA-Z][a-zA-Z0-9-]{0,%d}[a-zA-Z0-9]$`, inner))
	return func(name string) string {
		if !pattern.MatchString(name) {
			return fmt.Sprintf("Names must be 2 to %d letters, digits or hyphens, starting with a letter and ending with a letter or digit.", inner+2)
		}
		return ""
	}
}

// azureGrafanaVersions maps each supported major version to the release
// a workspace reports.
var azureGrafanaVersions = map[string]string{"10": "10.4.19", "11": "11.6.3", "12": "12.0.2"}

var azureGrafanaPlugins = []any{
	map[string]any{"pluginId": "grafana-azure-data-explorer-datasource", "name": "Azure Data Explorer Datasource", "type": "datasource", "author": "Grafana Labs"},
	map[string]any{"pluginId": "grafana-github-datasource", "name": "GitHub", "type": "datasource", "author": "Grafana Labs"},
	map[string]any{"pluginId": "marcusolsson-json-datasource", "name": "JSON API", "type": "datasource", "author": "Grafana Labs"},
}

func azureGrafanaValidate(payload map[string]any) string {
	sku := azureARMObject(payload["sku"])
	if !slices.Contains([]string{"Essential", "Standard"}, azureARMString(sku["name"])) {
		return "sku.name must be Essential or Standard."
	}
	if size, present := sku["size"]; present && (sku["name"] != "Standard" || (size != "X1" && size != "X2")) {
		return "sku.size must be X1 or X2, and only for the Standard SKU."
	}
	for _, check := range []func(map[string]any) string{
		azureEnumProperty("publicNetworkAccess", "Enabled", "Disabled"),
		azureEnumProperty("zoneRedundancy", "Enabled", "Disabled"),
		azureEnumProperty("apiKey", "Enabled", "Disabled"),
		azureEnumProperty("deterministicOutboundIP", "Enabled", "Disabled"),
		azureEnumProperty("creatorCanAdmin", "Enabled", "Disabled"),
		azureEnumProperty("autoGeneratedDomainNameLabelScope", "TenantReuse"),
	} {
		if msg := check(payload); msg != "" {
			return msg
		}
	}
	props := azureARMObject(payload["properties"])
	if raw, present := props["grafanaMajorVersion"]; present && azureGrafanaVersions[azureARMString(raw)] == "" {
		return "properties.grafanaMajorVersion must be 10, 11 or 12."
	}
	for i, raw := range azureARMSlice(azureARMObject(props["grafanaIntegrations"])["azureMonitorWorkspaceIntegrations"]) {
		if !strings.Contains(strings.ToLower(azureARMString(azureARMObject(raw)["azureMonitorWorkspaceResourceId"])), "/providers/microsoft.monitor/accounts/") {
			return fmt.Sprintf("properties.grafanaIntegrations.azureMonitorWorkspaceIntegrations[%d].azureMonitorWorkspaceResourceId must be an Azure Monitor workspace ID.", i)
		}
	}
	smtp := azureARMObject(azureARMObject(props["grafanaConfigurations"])["smtp"])
	if smtp["enabled"] == true && (azureARMString(smtp["host"]) == "" || azureARMString(smtp["fromAddress"]) == "") {
		return "properties.grafanaConfigurations.smtp needs a host and fromAddress when enabled."
	}
	if raw, present := smtp["startTLSPolicy"]; present && !slices.Contains([]string{"OpportunisticStartTLS", "MandatoryStartTLS", "NoStartTLS"}, azureARMString(raw)) {
		return "properties.grafanaConfigurations.smtp.startTLSPolicy must be OpportunisticStartTLS, MandatoryStartTLS or NoStartTLS."
	}
	return ""
}

// azureGrafanaProperties reports the workspace's endpoint and version, with
// Azure's defaults, and two stable outbound addresses when deterministic
// outbound IPs are enabled.
func azureGrafanaProperties(rec *azureARMResource) map[string]any {
	sum := sha256.Sum256([]byte(azureARMKey(rec.ID)))
	props := map[string]any{
		"endpoint":                   fmt.Sprintf("https://%s-%x.%s.grafana.azure.com", strings.ToLower(rec.Name), sum[:3], azureLocationHost(rec.Location)),
		"privateEndpointConnections": []any{},
	}
	defaults := map[string]any{
		"publicNetworkAccess": "Enabled", "zoneRedundancy": "Disabled", "apiKey": "Disabled",
		"deterministicOutboundIP": "Disabled", "autoGeneratedDomainNameLabelScope": "TenantReuse", "grafanaMajorVersion": "11",
	}
	for key, value := range defaults {
		if _, present := rec.Properties[key]; !present {
			props[key] = value
		}
	}
	major := azureARMString(rec.Properties["grafanaMajorVersion"])
	if azureGrafanaVersions[major] == "" {
		major = "11"
	}
	props["grafanaVersion"] = azureGrafanaVersions[major]
	if rec.Properties["deterministicOutboundIP"] == "Enabled" {
		props["outboundIPs"] = []any{fmt.Sprintf("20.%d.%d.%d", sum[3], sum[4], 1+int(sum[5])%254), fmt.Sprintf("20.%d.%d.%d", sum[6], sum[7], 1+int(sum[8])%254)}
	}
	return props
}

func azureGrafanaManagedPrivateEndpointValidate(payload map[string]any) string {
	props := azureARMObject(payload["properties"])
	if !strings.Contains(strings.ToLower(azureARMString(props["privateLinkResourceId"])), "/providers/") {
		return "properties.privateLinkResourceId must be a resource ID."
	}
	groups := azureARMSlice(props["groupIds"])
	if !strings.Contains(strings.ToLower(azureARMString(props["privateLinkResourceId"])), "/providers/microsoft.network/privatelinkservices/") && len(groups) == 0 {
		return "properties.groupIds must name the target sub-resource, such as blob or sqlServer."
	}
	return ""
}

func azureGrafanaIntegrationFabricValidate(payload map[string]any) string {
	props := azureARMObject(payload["properties"])
	for _, key := range []string{"targetResourceId", "dataSourceResourceId"} {
		if !strings.Contains(strings.ToLower(azureARMString(props[key])), "/providers/") {
			return "properties." + key + " must be a resource ID."
		}
	}
	if len(azureARMSlice(props["scenarios"])) == 0 {
		return "properties.scenarios must list at least one scenario."
	}
	return ""
}
